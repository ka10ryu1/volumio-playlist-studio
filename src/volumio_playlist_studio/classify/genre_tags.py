def genre_from_tag(tag: str | None) -> Genre | None:
    """タグのジャンル表記を正規化する。

    どの候補にも当てはまらない表記は、推測で「その他」とせず None（不明）を返す。
    """
    if tag is None or not tag.strip():
        return None

    for genre, pattern in _GENRE_PATTERNS:
        if pattern.search(tag):
            return genre

    return None
